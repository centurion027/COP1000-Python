class Book:
  def __init__(self, title, author, availability):
    self.title = title
    self.author = author
    self.availability = availability

  def display_info(self):
    print(f"Title: {self.title}\nAuthor: {self.author}\nAvailability status: {self.availability}\n")

  def check_out(self):
    self.availability = False

book1 = Book("Harry Potter", "J. K. Rowling", True)
book2 = Book("1984", "George Orwell", True)
book3 = Book("The Hobbit", "J. R. R. Tolkien", True)

books = [book1, book2, book3]

# Display the library catalog
print("Library Catalog\n")

for book in books:
  book.display_info()

book2.check_out()

# Display the updated library catalog after checkout
print("Updated Library Catalog\n")

for book in books:
  book.display_info()