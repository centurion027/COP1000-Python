import csv

#Creates the CSV File
with open("activity_log.csv", "w") as file:
  activities = csv.writer(file)
  activities.writerow(["Activity", "Minutes"])
  print("Activity Data Logger\n")

  #Adds the 3 rows
  for i in range(3):
    activity_name = input(f"Enter activity {i + 1}: ")
    minutes = int(input(f"Minutes: "))
    activities.writerow([activity_name, minutes])

print("Data saved successfully.\n")
print("--- Saved Activity Log ---\n")

#Reads the CSV
with open("activity_log.csv", "r") as file:
    activities = csv.reader(file)
    next(activities)

    for activity in activities:
        print(f"Activity: {activity[0]} | Minutes: {activity[1]}")